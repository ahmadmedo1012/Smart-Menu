-- P42-W3 (قرار المالك عبر IM، 2026-11-02): الأرشفة الحقيقية للأصناف.
--
-- العمود: "archivedAt" TIMESTAMP(3) NULL
--   NULL = غير مؤرشف (السلوك القديم حرفيًا — كل الاستعلامات القائمة لا تتغير).
--   NOT NULL = مؤرشف — يغادر كل واجهة عامة (صفحة المنيو، API الجوال، تقديم
--   الطلبات، المعرض المميز، سقف أصناف الباقة) بينما يبقى صف الـMenuItem نفسه
--   وسجله المرتبط (OrderItem Restrict · Review · stats) كاملًا غير ممسوس.
--
-- لا فهرس جديد: الاستعلامات العامة تُقيَّد أصلًا بالفئة (‎@@index([categoryId, sortOrder])‎)
-- و"archivedAt" IS NULL مرشِّح متبقٍّ على مجموعات صغيرة لكل فئة؛ استعلام
-- لوحة الأرشيف (‎archivedAt IS NOT NULL‎) عبر المطعم كله نادر وإداري.
--
-- إصلاح البيانات (المرة الوحيدة): أرشفة أصناف الاختبار الأربعة المثبتة —
-- قرار المالك الصريح بديلًا عن الحذف (الخيار أ في الدليل رُفض؛ الطلبات
-- المختلطة الـ13 «بيانات يجب الحفاظ عليها»). التحديث محروس بالتعريف الثلاثي
-- (المعرّف + الاسم + المستأجر عبر الفئة): أي انحراف = لا صف يُلمس (no-op)
-- والحارس الليلي demo-canary هو كاشف الحالة. في قواعد التطوير/الاختبار هذه
-- المعرّفات غير موجودة أصلًا → no-op نظيف.

ALTER TABLE "MenuItem" ADD COLUMN "archivedAt" TIMESTAMP(3);

-- الأصناف الأربعة المثبتة (متحقق منها حيًّا في جلسة P42-W2، 2026-11-02):
--   al-waha-cafe (102):      712 «كابتشينو اختبار 2» · 767 «TestLimitItem»
--   al-waha-cafe-demo (312): 778 «كابتشينو اختبار 2» · 779 «TestLimitItem»
-- بعد الأرشفة: المرجعيات المتبقية عليها = 13 صف OrderItem بالضبط (طلبات
-- مختلطة محفوظة) — العلاقات كلها تبقى سليمة لأن الصفوف لا تُحذف.
UPDATE "MenuItem" m
SET "archivedAt" = now()
FROM "MenuCategory" c
WHERE m."categoryId" = c.id
  AND c."restaurantId" IN (102, 312)
  AND m.id IN (712, 767, 778, 779)
  AND m.name IN ('TestLimitItem', 'كابتشينو اختبار 2')
  AND m."archivedAt" IS NULL
RETURNING m.id, m.name;
