-- r138 (W5-C3 — صدق الفاتورة): رسوم التوصيل المسحوبة على الطلب تُوثَّق على
-- صف الطلب نفسه.
--
-- قبل r138: POST /api/orders يطوي feeTotal داخل total (r137) لكنها لا
-- تُخزَّن في أي عمود — مستندات المالك (تحويل واتساب /api/whatsapp/generate،
-- نص النسخ buildOrderShareText، صفحة تفاصيل الطلب) تُظهر «المجموع» لا
-- تفسّره أسطرها (الأسطر تجمع إلى subtotal بينما الإجمالي subtotal+fee)،
-- بينما إيصال الزبون يُفرد سطر الرسوم — المستندان لنفس الطلب يتعارضان
-- بنيويًا. ولا يمكن إعادة بناء الرسوم لاحقًا: تغيير رسوم المطعم كان
-- يفسّر الطلبات القديمة تفسيرًا خاطئًا رجعيًا.
--
-- العمود NULL-able عمداً: NULL = صف ما قبل r138 (الرسوم غير معروفة —
-- العرض لا يخترع لها قيمة أبدًا)، 0 = لا رسوم (داخل/سفري أو الميزة
-- مطفأة — «رسوم 0 مخزنة تعامل معاملة الإطفاء» قانون r137)، >0 = رسوم
-- أُضيفت. الكتابة من feeTotal الخادمية حصراً (نفس مبدأ إعادة التسعير
-- r102-A5 — لا يُوثق بإجمالي العميل أبدًا).
--
-- إضافي فقط: عمود واحد، لا تغيير بيانات، لا عمليات هدم. CHECK NOT VALID
-- (نمط r121/r137): غير سالب وبحدود العمود على الكتابات الجديدة فورًا،
-- دون إعادة فحص أي صف قائم (العمود يولد NULL كله).

ALTER TABLE "Order" ADD COLUMN "deliveryFee" DECIMAL(10,2);

ALTER TABLE "Order" ADD CONSTRAINT "zz_round138_order_deliveryfee_check" CHECK ("deliveryFee" IS NULL OR ("deliveryFee" >= 0 AND "deliveryFee" <= 99999999.99)) NOT VALID;
